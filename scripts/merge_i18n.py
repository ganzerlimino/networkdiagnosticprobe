def deep_merge(base: dict[str, Any], overlay: dict[str, Any]) -> dict[str, Any]:
    merged = deepcopy(base)
    for key, value in overlay.items():
        if key == "_meta":
            merged[key] = value
            continue
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def flatten_keys(data: dict[str, Any], prefix: str = "") -> list[str]:
    keys: list[str] = []
    for key, value in data.items():
        if key == "_meta":
            continue
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            keys.extend(flatten_keys(value, path))
        else:
            keys.append(path)
    return keys


def main() -> None:
    counts: dict[str, int] = {}
    for code in LOCALES:
        path = LOCALE_DIR / f"{code}.json"
        with path.open(encoding="utf-8") as handle:
            data = json.load(handle)

        overlay = deepcopy(ADDITIONS[code])
        overlay["_meta"] = {**data.get("_meta", {}), "version": 3}
        merged = deep_merge(data, overlay)

        with path.open("w", encoding="utf-8") as handle:
            json.dump(merged, handle, ensure_ascii=False, indent=2)
            handle.write("\n")

        counts[code] = len(flatten_keys(merged))

    for code in LOCALES:
        print(f"{code}.json: {counts[code]} keys (excluding _meta)")

    unique_counts = set(counts.values())
    if len(unique_counts) == 1:
        print(f"SUCCESS: all three locales have {unique_counts.pop()} keys")
    else:
        print(f"MISMATCH: key counts differ — {counts}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
